/// capture_test.dart — tokens: HARNESS_IMPORTS, DEVICE_ENTRIES, SHOT_ENTRIES,
/// OUT_DIR. Always regenerated.
const String kGoldenCaptureTestTemplate = r'''
// GENERATED by app_shots golden-scaffold. Do not edit — regenerated each run.
// Captures each shot at every mapped device size. Run PER SHOT from the app
// root (see SKILL.md Step 4.5) — never the whole file at once:
//   flutter test {{SELF_PATH}} --plain-name "capture <shot-id>" --fail-fast --timeout 30s
// Requires Flutter >=3.27.
import 'dart:io';
import 'dart:ui' as ui;

import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:flutter/rendering.dart';
import 'package:flutter_test/flutter_test.dart';

import 'status_bar.dart';
{{HARNESS_IMPORTS}}

class _GoldenDevice {
  const _GoldenDevice(
      this.id, this.width, this.height, this.dpr, this.inset, this.platform);
  final String id;
  final double width;
  final double height;
  final double dpr;
  final double inset;
  final TargetPlatform platform;
}

const _devices = <_GoldenDevice>[
{{DEVICE_ENTRIES}}
];

class _Shot {
  const _Shot(this.id, this.deviceIds, this.style, this.theme, this.build,
      this.preCapture);
  final String id;
  final List<String> deviceIds;
  final ShotStatusBarStyle style;
  final ThemeData Function() theme;
  final Widget Function() build;
  final Future<void> Function(WidgetTester) preCapture;
}

final _shots = <_Shot>[
{{SHOT_ENTRIES}}
];

void main() {
  for (final shot in _shots) {
    for (final device
        in _devices.where((d) => shot.deviceIds.contains(d.id))) {
      testWidgets('capture ${shot.id} @ ${device.id}', (tester) async {
        // Real shadows in marketing captures (flutter_test stubs them by
        // default). Toggled per-test (not via setUpAll/tearDownAll):
        // flutter_test's _verifyInvariants() runs after every individual
        // test, not once after the whole suite, so a suite-scoped toggle
        // false-fails every test except the one active when tearDownAll
        // finally resets it.
        debugDisableShadows = false;
        debugDefaultTargetPlatformOverride = device.platform;
        // Everything that can throw (precacheImage, pumpAndSettle, toImage,
        // ...) lives in this try so the resets below always run in
        // `finally` — not via addTearDown: flutter_test's
        // _verifyInvariants() runs before addTearDown callbacks and asserts
        // these are back to defaults, so an addTearDown-based reset always
        // false-fails the test. A bare reset at the end of the try body has
        // the right timing but isn't exception-safe: any throw above it
        // skips the reset and false-fails every subsequent capture test too.
        try {
          tester.view.physicalSize = Size(device.width, device.height);
          tester.view.devicePixelRatio = device.dpr;
          addTearDown(tester.view.reset);

          final captureKey = GlobalKey();
          await tester.pumpWidget(RepaintBoundary(
            key: captureKey,
            child: AppShotsChrome(
              theme: shot.theme(),
              statusBarStyle: shot.style,
              statusBarInset: device.inset,
              isIos: device.platform == TargetPlatform.iOS,
              child: shot.build(),
            ),
          ));

          // Drain image decodes the fake test clock never completes. Only
          // deterministic bundled providers are precached; File/Network/custom
          // providers can hang the real clock (no timeout), so they are skipped
          // (mock them as Image.memory/Image.asset). Each precache is
          // additionally timeout-guarded so even a bundled provider can't block.
          await tester.runAsync(() async {
            for (final element in find.byType(Image).evaluate()) {
              final provider = (element.widget as Image).image;
              if (provider is! AssetBundleImageProvider &&
                  provider is! MemoryImage) {
                debugPrint('APP_SHOTS_WARNING: skipped precache of non-bundled '
                    'image ($provider); mock it as Image.memory/Image.asset');
                continue;
              }
              try {
                await precacheImage(provider, element)
                    .timeout(const Duration(seconds: 5));
              } catch (e) {
                debugPrint('APP_SHOTS_WARNING: precache failed/timed out for '
                    '$provider ($e)');
              }
            }
          });
          try {
            await tester.pumpAndSettle(const Duration(milliseconds: 100),
                EnginePhase.sendSemanticsUpdate, const Duration(seconds: 10));
          } on FlutterError {
            // Infinite animation: capture a fixed frame instead.
            await tester.pump(const Duration(milliseconds: 600));
            debugPrint('APP_SHOTS_WARNING pumpAndSettle timed out for '
                '${shot.id}@${device.id}; captured fixed 600ms frame');
          }
          await shot.preCapture(tester);
          await tester.pump();

          final boundary = captureKey.currentContext!.findRenderObject()!
              as RenderRepaintBoundary;
          await tester.runAsync(() async {
            final image = await boundary.toImage(pixelRatio: device.dpr);
            final bytes =
                await image.toByteData(format: ui.ImageByteFormat.png);
            final file = File('{{OUT_DIR}}/${shot.id}/${device.id}.png');
            file.parent.createSync(recursive: true);
            file.writeAsBytesSync(bytes!.buffer.asUint8List());
          });
        } finally {
          debugDefaultTargetPlatformOverride = null;
          debugDisableShadows = true;
        }
      });
    }
  }
}
''';

/// Renders capture_test.dart. [shots] pairs each plan shot with its import
/// prefix and resolved device classes; [devices] is the deduplicated union of
/// capture targets used by at least one shot.
String renderGoldenCaptureTest({
  required List<({String id, String prefix, List<String> deviceClasses})> shots,
  required List<StoreTarget> devices,
  required String outDir,
  required String selfPath,
}) {
  final harnessImports = shots
      .map((s) => "import 'harness/${s.prefix}.dart' as ${s.prefix};")
      .join('\n');
  final deviceEntries = devices.map((t) {
    final c = t.capture!;
    final platform = c.isIos ? 'TargetPlatform.iOS' : 'TargetPlatform.android';
    return "  _GoldenDevice('${t.deviceClass}', ${t.width}, "
        '${t.height}, ${c.dpr}, ${c.statusBarInsetPt}, $platform),';
  }).join('\n');
  final shotEntries = shots.map((s) {
    final ids = s.deviceClasses.map((d) => "'$d'").join(', ');
    return "  _Shot('${s.id}', [$ids], ${s.prefix}.statusBarStyle, "
        '${s.prefix}.buildTheme, ${s.prefix}.buildShot, '
        '${s.prefix}.preCapture),';
  }).join('\n');
  return renderFlow(kGoldenCaptureTestTemplate, {
    'HARNESS_IMPORTS': harnessImports,
    'DEVICE_ENTRIES': deviceEntries,
    'SHOT_ENTRIES': shotEntries,
    'OUT_DIR': outDir,
    'SELF_PATH': selfPath,
  });
}
