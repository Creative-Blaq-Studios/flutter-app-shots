/// Renders flutter_test_config.dart for the target app.
String renderGoldenTestConfig({
  required String goldenDir,
  required bool useGoogleFonts,
}) {
  return renderFlow(kGoldenTestConfigTemplate, {
    'GOLDEN_DIR': goldenDir,
    'GOOGLE_FONTS_IMPORT': useGoogleFonts
        ? "import 'package:google_fonts/google_fonts.dart';"
        : '',
    'GOOGLE_FONTS_CONFIG': useGoogleFonts
        ? '  // GoogleFonts.* app calls load through AssetManifest, not the\n'
            '  // app_shots FontLoader. Bundle direct-call fonts under\n'
            '  // google_fonts/ and include google_fonts/ in pubspec.yaml assets.\n'
            '  GoogleFonts.config.allowRuntimeFetching = false;'
        : '',
  });
}

