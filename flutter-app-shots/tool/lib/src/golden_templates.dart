/// Deterministic synthetic status bar. Glyphs are CustomPaint (no icon
/// fonts), so rendering is identical on every machine.
class AppShotsStatusBar extends StatelessWidget {
  const AppShotsStatusBar({
    super.key,
    required this.style,
    required this.isIos,
    required this.inset,
  });

  final ShotStatusBarStyle style;
  final bool isIos;
  final double inset;

  @override
  Widget build(BuildContext context) {
    final color = style == ShotStatusBarStyle.light
        ? Colors.white
        : const Color(0xDD000000);
    // Clock band: Dynamic Island iPhones center content in the upper ~54pt;
    // notch iPhones in ~32pt; small insets (iPad/Android) fill the band.
    final band = inset >= 59.0 ? 54.0 : (inset >= 44.0 ? 32.0 : inset);
    return Align(
      alignment: Alignment.topCenter,
      child: SizedBox(
        height: band,
        child: Padding(
          padding: EdgeInsets.symmetric(horizontal: isIos ? 28.0 : 12.0),
          child: Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Text('9:41',
                style: TextStyle(
                  color: color,
                  fontSize: isIos ? 16.0 : 13.0,
                  fontWeight: FontWeight.w600,
                  letterSpacing: isIos ? -0.3 : 0,
                ),
              ),
              CustomPaint(
                size: const Size(68, 12),
                painter: _StatusGlyphsPainter(color),
              ),
            ],
          ),
        ),
      ),
    );
  }
}

class _StatusGlyphsPainter extends CustomPainter {
  const _StatusGlyphsPainter(this.color);
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final fill = Paint()
      ..color = color
      ..style = PaintingStyle.fill;
    // Cellular: four ascending bars.
    for (var i = 0; i < 4; i++) {
      final h = 4.0 + i * 2.5;
      canvas.drawRRect(
        RRect.fromRectAndRadius(
          Rect.fromLTWH(i * 5.0, size.height - h, 3.5, h),
          const Radius.circular(1),
        ),
        fill,
      );
    }
    // Wifi: three arcs + dot.
    final stroke = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.8
      ..strokeCap = StrokeCap.round;
    final c = Offset(32, size.height - 1.5);
    for (var i = 0; i < 3; i++) {
      final r = 2.5 + i * 3.2;
      canvas.drawArc(
        Rect.fromCircle(center: c, radius: r),
        -2.35619449, // -3π/4
        1.57079633, // π/2 sweep
        false,
        stroke,
      );
    }
    canvas.drawCircle(c, 1.4, fill);
    // Battery: outline + full charge + nub.
    final outline = Paint()
      ..color = color.withValues(alpha: 0.45)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1;
    canvas.drawRRect(
      RRect.fromRectAndRadius(
        Rect.fromLTWH(44, size.height - 11.5, 21, 11),
        const Radius.circular(2.5),
      ),
      outline,
    );
    canvas.drawRRect(
      RRect.fromRectAndRadius(
        Rect.fromLTWH(45.5, size.height - 10, 18, 8),
        const Radius.circular(1.5),
      ),
      fill,
    );
    canvas.drawRRect(
      RRect.fromRectAndRadius(
        Rect.fromLTWH(65.8, size.height - 7.5, 1.6, 3),
        const Radius.circular(1),
      ),
      fill,
    );
  }

  @override
  bool shouldRepaint(covariant _StatusGlyphsPainter old) => old.color != color;
}
''';

/// flutter_test_config.dart — tokens: GOLDEN_DIR, GOOGLE_FONTS_IMPORT,
/// GOOGLE_FONTS_CONFIG. Always regenerated.
const String kGoldenTestConfigTemplate = r'''
// GENERATED by app_shots golden-scaffold. Do not edit — regenerated each run.
// Loads real fonts before any capture test runs: every directory under
// {{GOLDEN_DIR}}/fonts/ is registered as one font family (directory name =
// family name, which must exactly match TextStyle.fontFamily).
// Requires Flutter >=3.27.
import 'dart:async';
import 'dart:io';
import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
{{GOOGLE_FONTS_IMPORT}}

Future<void> testExecutable(FutureOr<void> Function() testMain) async {
  TestWidgetsFlutterBinding.ensureInitialized();
  await _loadAppShotsFonts();
{{GOOGLE_FONTS_CONFIG}}
  await testMain();
}

Future<void> _loadAppShotsFonts() async {
  // Material icon glyphs (Icons.add, etc.) come from the framework's own
  // bundled MaterialIcons font, which plain `flutter test` never loads —
  // without this, every icon renders as a tofu/missing-glyph box. This is
  // the same approach golden_toolkit historically used.
  try {
    final materialIcons = FontLoader('MaterialIcons')
      ..addFont(rootBundle.load('fonts/MaterialIcons-Regular.otf'));
    await materialIcons.load();
  } catch (e) {
    debugPrint('APP_SHOTS_WARNING: failed to load MaterialIcons font ($e); '
        'icon glyphs may render as tofu in this environment.');
  }

  final fontsDir = Directory('{{GOLDEN_DIR}}/fonts');
  if (!fontsDir.existsSync()) return;
  for (final entry in fontsDir.listSync()..sort((a, b) => a.path.compareTo(b.path))) {
    if (entry is! Directory) continue;
    final family = entry.uri.pathSegments.lastWhere((s) => s.isNotEmpty);
    final loader = FontLoader(family);
    for (final file in entry.listSync().whereType<File>().toList()
      ..sort((a, b) => a.path.compareTo(b.path))) {
      if (file.path.endsWith('.ttf') || file.path.endsWith('.otf')) {
        final bytes = file.readAsBytesSync();
        loader.addFont(Future.value(ByteData.sublistView(bytes)));
      }
    }
    await loader.load();
  }
}
''';

